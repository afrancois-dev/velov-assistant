"""LLM evaluation: LLM-as-a-judge comparing the RAG answer to the ground-truth answer.

Inspired by the llm-zoomcamp A->Q->A' evaluation: the judge decides whether the AI
answer is semantically equivalent to the original FAQ answer (good) or not (bad),
and explains its verdict. See 04-evaluation/lessons/13-llm-as-judge.md.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, Field
from tenacity import retry, stop_after_attempt, wait_exponential

from app.config import settings
from app.main import _run_chat
from app.rag.llm import get_client

GROUND_TRUTH = Path(__file__).resolve().parent / "data" / "ground_truth.json"
FAQ = Path(__file__).resolve().parent.parent / "data" / "faq" / "faq.json"

JUDGE_INSTRUCTIONS = """
You are an expert evaluator. You will be given:
1. A question from a student
2. The original answer from the FAQ (ground truth)
3. An answer generated by an AI assistant

Your task is to decide if the AI answer is semantically equivalent to
the original answer.

Rules:
- The AI answer does NOT need to be word-for-word identical
- It should convey the same key information
- Extra detail is fine as long as the core answer is correct
- Mark 'bad' only if the AI answer is wrong or misses the key point

Be fair and focus on correctness, not style.
""".strip()

JUDGE_PROMPT = """
Question:
{question}

Original Answer (ground truth):
{answer_orig}

AI Answer:
{answer_llm}

Respond in JSON with the fields "reasoning" and "score".
""".strip()


class AnswerEvaluation(BaseModel):
    reasoning: str = Field(description="Reasoning about the quality of the answer.")
    score: Literal["good", "bad"] = Field(description="'good' if the answer is correct and complete, 'bad' otherwise.")


@lru_cache(maxsize=1)
def _load() -> list[dict]:
    return json.loads(GROUND_TRUTH.read_text())


@lru_cache(maxsize=1)
def _faq() -> dict[str, str]:
    return {d["id"]: d["answer"] for d in json.loads(FAQ.read_text())}


@retry(stop=stop_after_attempt(3), wait=wait_exponential(min=1, max=8))
def _judge(question: str, answer_orig: str, answer_llm: str) -> AnswerEvaluation:
    content = (
        get_client()
        .chat.completions.create(
            model=settings.llm_model,
            messages=[
                {"role": "system", "content": JUDGE_INSTRUCTIONS},
                {
                    "role": "user",
                    "content": JUDGE_PROMPT.format(question=question, answer_orig=answer_orig, answer_llm=answer_llm),
                },
            ],
            temperature=0.0,
            response_format={"type": "json_object"},
        )
        .choices[0]
        .message.content
    )
    return AnswerEvaluation.model_validate(json.loads(content or "{}"))


def judge(question: str, answer_orig: str, answer_llm: str) -> AnswerEvaluation:
    return _judge(question=question, answer_orig=answer_orig, answer_llm=answer_llm)


def _generate_answer(question: str) -> str:
    answer, *_ = _run_chat(question)
    return answer


def _records() -> list[dict]:
    faq = _faq()
    return [
        {"question": item["question"], "answer_orig": faq[item["document"]], "answer_llm": _generate_answer(item["question"])}
        for item in _load()
    ]


def main() -> None:
    records = _records()
    results = [judge(**r) for r in records]
    good = sum(r.score == "good" for r in results)
    print(f"good: {good}/{len(records)} = {good / len(records):.2%}")
    for record, result in zip(records, results):
        if result.score == "bad":
            print(
                f"\nBAD — {record['question']}\n"
                f"  original: {record['answer_orig'][:120]}\n"
                f"  llm: {record['answer_llm'][:120]}\n"
                f"  reasoning: {result.reasoning}"
            )


if __name__ == "__main__":
    main()
